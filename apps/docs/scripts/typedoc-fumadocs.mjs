import { writeFile } from "node:fs/promises"
import { MarkdownPageEvent } from "typedoc-plugin-markdown"

const pageDescription = (name) =>
  name === "effect-state-machine API"
    ? "Generated reference for every public effect-state-machine module."
    : `Generated reference for the public ${name} module.`

const apiRoute = (page) =>
  page === "index" ? "/docs/reference/api" : `/docs/reference/api/${page}`

const rewriteMdxLinks = (markdown) =>
  markdown.replace(
    /\]\(([^/)\n]+)\.mdx((?:#[^)\n]*)?)\)/g,
    (_match, page, hash) => `](${apiRoute(page)}${hash})`,
  )

/** @param {import("typedoc-plugin-markdown").MarkdownApplication} app */
export function load(app) {
  app.renderer.markdownHooks.on(
    "page.begin",
    () => "{/* Generated by `pnpm docs:api`. Do not edit by hand. */}\n\n",
  )

  app.renderer.on(MarkdownPageEvent.BEGIN, (page) => {
    const name = page.model?.name ?? "effect-state-machine API"
    page.frontmatter = {
      title: name === "effect-state-machine API" ? "API reference" : `${name} API`,
      description: pageDescription(name),
      full: true,
      ...page.frontmatter,
    }
  })

  app.renderer.on(MarkdownPageEvent.END, (page) => {
    page.contents = rewriteMdxLinks(page.contents)
  })

  app.renderer.postMarkdownRenderAsyncJobs.push(async () => {
    const metadata = {
      title: "Generated API",
      pages: [
        "index",
        "Machine",
        "MachineEngine",
        "MachineStore",
        "LocalStorageMachineStore",
        "MachineWorkflow",
        "Graph",
        "Mermaid",
        "SourceLocation",
      ],
    }
    await writeFile(
      new URL("../content/docs/reference/api/meta.json", import.meta.url),
      `${JSON.stringify(metadata, null, 2)}\n`,
    )
  })
}
